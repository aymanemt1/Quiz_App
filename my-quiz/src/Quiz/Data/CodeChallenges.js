// Challenges of the code-heavy stacks, optionally filtered by topic + level, sorted easy -> hard
export const getCodeChallenges = (langTrans, topic = "All", level = "all") => {
  const block = codeChallenges.find((b) => b.lang === langTrans);
  if (!block) return [];
  let qs = [...block.challenges];
  if (topic && topic !== "All") qs = qs.filter((q) => q.topic === topic);
  if (level !== "all") qs = qs.filter((q) => q.level === Number(level));
  return qs
    .sort((a, b) => (a.level || 1) - (b.level || 1))
    .map((q, i) => ({ ...q, id: i, selection: null }));
};
